#!/usr/bin/env node
/**
 * Forgotten-export gate — a type in a PUBLIC signature that a consumer cannot name.
 *
 * ## The bug this exists to stop
 *
 * A class is exported; one of its method parameters is typed with a local alias
 * that never reaches an entry. Callers can pass a literal:
 *
 *     builder.sort({ createdAt: "desc" })          // fine — inferred
 *
 * but cannot declare one:
 *
 *     const spec: ??? = { createdAt: "desc" }      // no importable name
 *
 * Found in `@classytic/mongokit` (`AggregationBuilder.sort`), where the only
 * importable `SortSpec` was a NARROWER type that rejected the value the method
 * actually accepts — so the obvious guess was also the wrong one.
 *
 * Nothing else catches it. `tsc` is happy: the type is reachable inside the
 * bundle. `knip` reports the opposite direction (exports nobody imports).
 * `check:api-surface` snapshots the surface that EXISTS — it cannot know a type
 * is missing from it. `publint` / `attw` check resolution and module format.
 *
 * ## Why this is a text scanner and not a TypeScript AST walk
 *
 * Arc is on TypeScript 7, which no longer exposes the compiler API from the
 * `typescript` entry — only `version`. The AST lives behind `unstable/ast`, and
 * that module ships node predicates but NO standalone parser: parsing sits in
 * the project/LSP-oriented `unstable/sync` API, which needs a tsconfig and a
 * language service to read one generated file. Depending on an explicitly
 * unstable surface inside a release gate trades one fragility for a worse one.
 *
 * So this reads the generated `.d.mts` as text, exactly like
 * `check-boundaries.mjs` reads imports. That is sound because the input is
 * machine-generated by rolldown-dts: one declaration per line, two-space member
 * indentation, closing braces at column 0. It is not a general TypeScript
 * parser and does not need to be.
 *
 * ## What it checks
 *
 *   1. every declaration across ALL of `dist` — entries AND shared chunks,
 *      because tsdown hoists shared declarations out of the entry file;
 *   2. a name counts as exported if it is declared `export`ed OR appears on the
 *      LOCAL side of an export clause anywhere — chunks re-export under short
 *      aliases (`export { QueryCache as i }`), so matching the local name is
 *      what survives that rewriting;
 *   3. type names in an exported class method's or function's PARAMETER and
 *      RETURN positions, reported when declared locally but never exported.
 *
 * Parameter/return only, deliberately: a type nested inside an exported type's
 * body is reachable by naming its parent, but a parameter type is something the
 * caller must construct and hold.
 *
 * Run: node scripts/check-forgotten-exports.mjs   (after `npm run build`)
 */

import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const ROOT = process.cwd();
const DIST = path.join(ROOT, "dist");

/**
 * Down-only ratchet. Twenty-eight of these predate the check, spread across
 * fifteen entries — converting them all is a public-surface change that does not
 * belong in a release, and a gate that blocks every commit gets deleted rather
 * than satisfied. Non-growth is enforceable today and converges.
 *
 * LOWER as they are fixed. At 0 the rule is absolute and this constant can go.
 * Do not raise it: a rise means a NEW public signature is unnameable.
 */
const BASELINE = 28;

/** TypeScript/ES built-ins never declared by us — cheap pre-filter. */
const BUILTIN =
  /^(Array|Awaited|BigInt|Boolean|Buffer|Capitalize|Date|Error|Exclude|Extract|Function|InstanceType|Iterable|AsyncIterable|IterableIterator|Map|NonNullable|Number|Object|Omit|Parameters|Partial|Pick|Promise|PromiseLike|Readonly|ReadonlyArray|ReadonlyMap|ReadonlySet|Record|RegExp|Required|Return[A-Za-z]*|Set|String|Symbol|This[A-Za-z]*|Uint8Array|WeakMap|WeakSet|NoInfer|Uppercase|Lowercase)$/;

function distFiles(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) distFiles(full, out);
    else if (entry.endsWith(".d.mts") || entry.endsWith(".d.ts")) out.push(full);
  }
  return out;
}

const DECL =
  /^(export\s+)?declare\s+(?:abstract\s+)?(class|function|const)\s+([A-Za-z_$][\w$]*)/;
const TYPE_DECL = /^(export\s+)?(?:declare\s+)?(type|interface)\s+([A-Za-z_$][\w$]*)/;
/** `name(args): Ret;` or `name<T>(args): Ret;` at member indentation. */
const MEMBER_SIG = /^\s{2}(?:readonly\s+|static\s+|abstract\s+|private\s+|protected\s+)*([A-Za-z_$][\w$]*)\s*(?:<[^(]*>)?\s*\((.*)\)\s*:\s*(.+?);\s*$/;
const FN_SIG = /^(?:export\s+)?declare\s+function\s+([A-Za-z_$][\w$]*)\s*(?:<[^(]*>)?\s*\((.*)\)\s*:\s*(.+?);\s*$/;

const files = distFiles(DIST);
if (files.length === 0) {
  console.error("✖ No built .d.mts files found — run `npm run build` first.");
  process.exit(1);
}

const declared = new Set();
const exported = new Set();
const parsed = [];

for (const file of files) {
  const lines = readFileSync(file, "utf8").split(/\r?\n/);
  parsed.push({ file, lines });
  for (const line of lines) {
    const d = DECL.exec(line) ?? TYPE_DECL.exec(line);
    if (d) {
      declared.add(d[3]);
      if (d[1]) exported.add(d[3]);
    }
    // `export { Local as alias, Other };` — the LOCAL side is what is declared.
    if (/^export\s*\{/.test(line)) {
      for (const spec of line.replace(/^export\s*\{/, "").replace(/\}.*$/, "").split(",")) {
        const local = spec.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0]?.trim();
        if (local) exported.add(local);
      }
    }
  }
}

/** Type identifiers in a parameter list / return type. */
function typeNames(text) {
  const out = new Set();
  for (const m of text.matchAll(/\b([A-Z][\w$]*)\b/g)) {
    const name = m[1];
    if (!BUILTIN.test(name)) out.add(name);
  }
  return out;
}

const findings = new Map();

for (const { file, lines } of parsed) {
  let inExportedClass = false;
  let className = "";

  for (const line of lines) {
    // Track the body of an exported class; generated output closes at column 0.
    const cls = /^(export\s+)?declare\s+(?:abstract\s+)?class\s+([A-Za-z_$][\w$]*)/.exec(line);
    if (cls) {
      className = cls[2];
      inExportedClass = Boolean(cls[1]) || exported.has(className);
      continue;
    }
    if (inExportedClass && /^\}/.test(line)) {
      inExportedClass = false;
      continue;
    }

    let owner;
    let params;
    let ret;
    const fn = FN_SIG.exec(line);
    if (fn && (line.startsWith("export ") || exported.has(fn[1]))) {
      owner = fn[1];
      params = fn[2];
      ret = fn[3];
    } else if (inExportedClass) {
      const m = MEMBER_SIG.exec(line);
      if (m) {
        owner = `${className}.${m[1]}()`;
        params = m[2];
        ret = m[3];
      }
    }
    if (owner === undefined) continue;

    for (const name of [...typeNames(params), ...typeNames(ret)]) {
      if (!declared.has(name) || exported.has(name)) continue;
      if (!findings.has(name)) findings.set(name, { owner, file });
    }
  }
}

for (const [name, { owner, file }] of findings) {
  console.error(`    ${name} — in ${owner}, ${path.relative(ROOT, file)}, but never exported`);
}

if (findings.size > BASELINE) {
  console.error(
    `\n✖ Forgotten exports: ${findings.size} (baseline ${BASELINE}).\n\n` +
      "A type in a public parameter or return position must be importable, or callers\n" +
      "can pass a literal but cannot declare a variable for it. Export it from the entry\n" +
      "(alias it if the name would collide).\n",
  );
  process.exit(1);
}

if (findings.size < BASELINE) {
  console.log(
    `check:forgotten-exports — ${findings.size} (baseline ${BASELINE}). ` +
      `Progress: LOWER BASELINE to ${findings.size} to lock it in.`,
  );
  process.exit(0);
}

console.log(
  findings.size === 0
    ? `✔ No forgotten exports — ${files.length} declaration file(s) scanned.`
    : `check:forgotten-exports — ${findings.size}, at baseline. No growth. ` +
        `(${files.length} declaration file(s) scanned.)`,
);
